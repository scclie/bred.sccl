import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, rmSync, chmodSync, copyFileSync } from 'node:fs';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { loadConfig } from '../../lib/config.mjs';
import { discoverModules, resolveSlots, applyOverrides } from '../../lib/modules.mjs';
import footer from '../../../modules/footer_text/generator.mjs';
import siteFooter from '../../../modules/site_footer/generator.mjs';
const root = new URL('../../../', import.meta.url).pathname;

test('successful build restores fences after release consumed the preprocessed source', () => {
  const fixture = mkdtempSync('/tmp/opencode/bred-restore-success-');
  try {
    for (const directory of ['content', 'assets', 'bin']) mkdirSync(join(fixture, directory));
    copyFileSync(join(root, 'assets/notizine.ziggy'), join(fixture, 'assets/notizine.ziggy'));
    const source = join(fixture, 'content/test.smd');
    const original = '```embed\nurl="https://example.org/video"\nheight=480\n```\n\n```mermaid\ngraph TD\n A --> B\n```\n';
    writeFileSync(source, original);
    const zine = join(fixture, 'bin/zine');
    writeFileSync(zine, `#!${process.execPath}\nconst fs = require('node:fs');\nfs.copyFileSync('content/test.smd', 'consumed.txt');\nfs.mkdirSync('public', { recursive: true });\nfs.writeFileSync('public/index.html', '<html><body>ok</body></html>');\n`);
    chmodSync(zine, 0o755);
    const result = spawnSync(process.execPath, [join(root, 'scripts/build.mjs'), '--skip-generate'], {
      cwd: fixture, encoding: 'utf8', env: { ...process.env, PATH: `${join(fixture, 'bin')}:${process.env.PATH}` },
    });
    assert.equal(result.status, 0, result.stderr + result.stdout);
    const consumed = readFileSync(join(fixture, 'consumed.txt'), 'utf8');
    assert.match(consumed, /<iframe/);
    assert.match(consumed, /height: 480px/);
    assert.match(consumed, /x_mermaid_block_0/);
    assert.equal(readFileSync(source, 'utf8'), original);
  } finally { rmSync(fixture, { recursive: true, force: true }); }
});

test('failed release restores both embed and mermaid fences byte for byte', () => {
  const fixture = mkdtempSync('/tmp/opencode/bred-restore-');
  try {
    mkdirSync(join(fixture, 'content'));
    const source = join(fixture, 'content/test.smd');
    const original = '```embed url="https://example.org/video" height=480\n```\n\n```mermaid\ngraph TD\n A --> B\n```\n';
    writeFileSync(source, original);
    const result = spawnSync(process.execPath, [join(root, 'scripts/build.mjs'), '--skip-generate'], {
      cwd: fixture, encoding: 'utf8', env: { ...process.env, PATH: '/nonexistent' },
    });
    assert.notEqual(result.status, 0);
    assert.match(result.stdout, /\[embed\] Preprocessed 1 files/);
    assert.match(result.stdout, /\[mermaid\] Preprocessed 1 files/);
    assert.match(result.stderr, /zine/);
    assert.equal(readFileSync(source, 'utf8'), original);
  } finally { rmSync(fixture, { recursive: true, force: true }); }
});

test('typed badge assets and inherited ru search composition resolve together', () => {
  const config = loadConfig(root);
  const modules = discoverModules(root);
  assert.equal(modules.badges.delivery, 'critical');
  assert.ok(modules.badges.assets.some(asset => asset.source === 'badges.css'));
  const { zones } = resolveSlots(config, modules);
  const ru = applyOverrides(zones, config.slots_overrides, '/ru/search/', modules);
  assert.ok(ru.top_center.flat().some(entry => entry.module === '_lang_nav'));
  assert.ok(ru.middle_center.flat().some(entry => entry.module === 'search'));
  assert.deepEqual(ru.middle_left.flat().map(entry => [entry.module, entry.params.section]), [['rated_recents', '/ru/posts/']]);
  assert.ok(ru.bottom_center.flat().some(entry => entry.module === 'site_footer'));
});

test('plain footer API is optional and escapes text without removing site attribution', async () => {
  assert.equal(await footer({ params: {} }), '');
  assert.equal(await footer({ params: { text: '<notes>' } }), '<p class="footer-text">&lt;notes&gt;</p>');
  assert.equal(await siteFooter({ i18n: key => ({ generated_by: 'Generated by', with: 'with' })[key] }, { GITHUB_SHA: '' }), '<p class="footer-text"><a href="https://sccl.cc">sccl.cc</a> | <span>Generated by</span> <a href="https://zine-ssg.io">zine</a> <span>with</span> <a href="https://git.sccl.cc/scclie/notizine">notizine</a></p>');
});

test('footer displays a short CI commit hash linking to the blog repository', async () => {
  const sha = '0123456789abcdef0123456789abcdef01234567';
  const html = await siteFooter({ i18n: key => key }, { GITHUB_SHA: sha });
  assert.match(html, /<a href="https:\/\/sccl\.cc">sccl\.cc<\/a> <a href="https:\/\/github\.com\/scclie\/bred\.sccl">0123456<\/a> \|/);
});

test('footer omits the commit link for an invalid supplied hash', async () => {
  for (const sha of ['', 'main', '0123456', '<script>alert(1)</script>']) {
    const html = await siteFooter({ i18n: key => key }, { GITHUB_SHA: sha });
    assert.doesNotMatch(html, /href="https:\/\/github\.com\/scclie\/bred\.sccl"|<script>/);
    assert.match(html, /sccl\.cc<\/a> \|/);
  }
});

test('local footer reads the current commit when no CI hash is supplied', async t => {
  const current = spawnSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' });
  // Source archives used by build fixtures have no Git metadata.
  if (current.status !== 0) return t.skip('source archive has no Git metadata');
  const sha = current.stdout.trim();
  const html = await siteFooter({ i18n: key => key }, {});
  assert.ok(html.includes(`<a href="https://github.com/scclie/bred.sccl">${sha.slice(0, 7)}</a>`));
});
